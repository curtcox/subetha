#!/usr/bin/env bash
#
# build-xcframework.sh - build sdk/swift/build/subetha_coreFFI.xcframework from sdk/core
# (macOS + Xcode + rustup). Package.swift declares the SubEthaCore product once it exists.
#
# Usage: sdk/swift/scripts/build-xcframework.sh [--macos-only] [--debug] [--zip]
#
#   --macos-only  only the host macOS slice (enough for `swift test`; what CI uses)
#   --debug       debug profile instead of release
#   --zip         also write build/subetha_coreFFI.xcframework.zip and print its SwiftPM
#                 checksum (for SUBETHA_CORE_XCFRAMEWORK_URL / _CHECKSUM releases)
#
# Slices: iOS device (arm64), iOS simulator (arm64 + x86_64), macOS (arm64 + x86_64).
# Headers: sdk/swift/ffi (generated by sdk/core/scripts/gen-bindings.sh).

set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
pkg="$(cd "$here/.." && pwd)"
root="$(cd "$pkg/../.." && pwd)"
macos_only=0
profile=release
zip=0
for arg in "$@"; do
  case "$arg" in
    --macos-only) macos_only=1 ;;
    --debug) profile=debug ;;
    --zip) zip=1 ;;
    -h|--help) sed -n '3,15p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "build-xcframework: unknown argument: $arg" >&2; exit 2 ;;
  esac
done

[ "$(uname -s)" = Darwin ] || { echo "build-xcframework: needs macOS + Xcode" >&2; exit 1; }

if [ "$macos_only" = 1 ]; then
  case "$(uname -m)" in
    arm64) targets=(aarch64-apple-darwin) ;;
    *) targets=(x86_64-apple-darwin) ;;
  esac
else
  targets=(aarch64-apple-ios aarch64-apple-ios-sim x86_64-apple-ios aarch64-apple-darwin x86_64-apple-darwin)
fi

rustup target add "${targets[@]}"
flags=(-p subetha-core --features uniffi --lib)
[ "$profile" = release ] && flags+=(--release)
cd "$root"
for t in "${targets[@]}"; do
  cargo build "${flags[@]}" --target "$t"
done

out="$pkg/build"
work="$out/work"
rm -rf "$work" "$out/subetha_coreFFI.xcframework"
mkdir -p "$work/headers"
cp "$pkg/ffi/subetha_coreFFI.h" "$pkg/ffi/module.modulemap" "$work/headers/"

lib() { echo "$root/target/$1/$profile/libsubetha_core.a"; }
fat() { # fat <name> <targets...>
  local name=$1; shift
  mkdir -p "$work/$name"
  local inputs=()
  for t in "$@"; do inputs+=("$(lib "$t")"); done
  lipo -create "${inputs[@]}" -output "$work/$name/libsubetha_core.a"
  echo "$work/$name/libsubetha_core.a"
}

args=()
if [ "$macos_only" = 1 ]; then
  args+=(-library "$(lib "${targets[0]}")" -headers "$work/headers")
else
  args+=(-library "$(lib aarch64-apple-ios)" -headers "$work/headers")
  args+=(-library "$(fat ios-sim aarch64-apple-ios-sim x86_64-apple-ios)" -headers "$work/headers")
  args+=(-library "$(fat macos aarch64-apple-darwin x86_64-apple-darwin)" -headers "$work/headers")
fi
xcodebuild -create-xcframework "${args[@]}" -output "$out/subetha_coreFFI.xcframework"
rm -rf "$work"
echo "build-xcframework: wrote $out/subetha_coreFFI.xcframework"

if [ "$zip" = 1 ]; then
  (cd "$out" && rm -f subetha_coreFFI.xcframework.zip && zip -qry subetha_coreFFI.xcframework.zip subetha_coreFFI.xcframework)
  echo "checksum: $(swift package compute-checksum "$out/subetha_coreFFI.xcframework.zip")"
fi
