// swift-tools-version:5.9
//
// SubEtha for Swift (iOS 15+, macOS 12+).
//
//   SubEtha      async/await client (URLSession). No native code.
//   SubEthaCore  the Rust core through UniFFI (device keys, envelope signatures, E2EE).
//                Needs build/subetha_coreFFI.xcframework (scripts/build-xcframework.sh;
//                CI builds it), so it is only declared when that exists or when
//                SUBETHA_CORE_XCFRAMEWORK_URL + _CHECKSUM point at a released zip.
import Foundation
import PackageDescription

let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
let localXCFramework = "build/subetha_coreFFI.xcframework"
let env = ProcessInfo.processInfo.environment

var coreBinary: Target?
if FileManager.default.fileExists(atPath: packageDir.appendingPathComponent(localXCFramework).path) {
    coreBinary = .binaryTarget(name: "subetha_coreFFI", path: localXCFramework)
} else if let url = env["SUBETHA_CORE_XCFRAMEWORK_URL"], let checksum = env["SUBETHA_CORE_XCFRAMEWORK_CHECKSUM"] {
    coreBinary = .binaryTarget(name: "subetha_coreFFI", url: url, checksum: checksum)
}

var products: [Product] = [
    .library(name: "SubEtha", targets: ["SubEtha"]),
]
var targets: [Target] = [
    .target(name: "SubEtha", path: "Sources/SubEtha"),
    .testTarget(name: "SubEthaTests", dependencies: ["SubEtha"], path: "Tests/SubEthaTests"),
]

if let coreBinary {
    products.append(.library(name: "SubEthaCore", targets: ["SubEthaCore"]))
    targets += [
        coreBinary,
        // Generated by sdk/core/scripts/gen-bindings.sh (do not edit).
        // getrandom uses SecRandomCopyBytes on iOS.
        .target(name: "SubEthaCoreFFI", dependencies: ["subetha_coreFFI"], path: "Sources/SubEthaCoreFFI",
                linkerSettings: [.linkedFramework("Security")]),
        .target(name: "SubEthaCore", dependencies: ["SubEtha", "SubEthaCoreFFI"], path: "Sources/SubEthaCore"),
        .testTarget(name: "SubEthaCoreTests", dependencies: ["SubEthaCore"], path: "Tests/SubEthaCoreTests"),
    ]
}

let package = Package(
    name: "SubEtha",
    platforms: [.iOS(.v15), .macOS(.v12)],
    products: products,
    targets: targets
)
